# ---------- χρονοδρομολόγηση χωρίς διακοπή ----------
def schedule(procs, alg):
    """procs: [(όνομα, άφιξη, εκτέλεση)] → (κομμάτια Gantt [(όνομα ή None, από, έως)], {όνομα: (αρχίζει, τελειώνει, αναμονή)})"""
    t, rem, segs, res = 0, list(procs), [], {}
    while rem:
        ready = [p for p in rem if p[1] <= t]
        if not ready:
            nt = min(p[1] for p in rem)
            segs.append((None, t, nt)); t = nt
            continue
        p = min(ready, key=(lambda p: p[1]) if alg == "fcfs" else (lambda p: (p[2], p[1])))
        segs.append((p[0], t, t + p[2]))
        res[p[0]] = (t, t + p[2], t - p[1])
        t += p[2]
        rem.remove(p)
    return segs, res

def num(x):
    return str(round(x)) if abs(x - round(x)) < 1e-9 else f"{x:.2f}".rstrip("0").replace(".", ",")

def avg_line(procs, res):
    w = [res[p[0]][2] for p in procs]
    return f"({' + '.join(map(str, w))}) / {len(w)} = **{num(sum(w) / len(w))}**"

# ---------- Gantt ----------
PC = {"P1": (BLUE, "FFFFFF"), "P2": ("5C73E6", "FFFFFF"), "P3": ("8EA0EE", INK), "P4": ("E8C773", INK)}
BAR_H = 457200

def tick(s, x, y, text):
    tf = box(s, x - 182880, y, 365760, 201168, MSO_ANCHOR.TOP)
    tf.paragraphs[0].alignment = PP_ALIGN.CENTER
    run(tf.paragraphs[0], str(text), 9, MUTED, MONO)

def gantt(s, x, y, w, segs):
    """γεμάτο διάγραμμα· επιστρέφει το κάτω όριο"""
    total = segs[-1][2]
    u = w / total
    for name, a, b in segs:
        fill, fg = PC.get(name, (PAPER, MUTED))
        sh = shape(s, int(x + a * u), y, int((b - a) * u), BAR_H, fill, "FFFFFF" if name else LINE)
        tf = sh.text_frame
        tf.margin_left = tf.margin_right = 0
        tf.paragraphs[0].alignment = PP_ALIGN.CENTER
        run(tf.paragraphs[0], name or "άδειος", 10 if name else 9, fg, MONO, bold=bool(name))
    for t in sorted({a for _, a, _ in segs} | {total}):
        tick(s, int(x + t * u), y + BAR_H + 27432, t)
    return y + BAR_H + 228600

def grid(s, x, y, w, total):
    """άδειο διάγραμμα για να το συμπληρώσει ο εκπαιδευόμενος"""
    u = w / total
    for i in range(total):
        shape(s, int(x + i * u), y, int(u), BAR_H, "FFFFFF", LINE)
    step_ = 1 if total <= 16 else 3
    for t in range(0, total + 1, step_):
        tick(s, int(x + t * u), y + BAR_H + 27432, t)
    return y + BAR_H + 228600

def data_table(s, x, y, procs, w=COL_W - 914400):
    rows = [["Διεργασία", "Άφιξη", "Εκτέλεση"]] + [[n, a, e] for n, a, e in procs]
    return table(s, x, y, [w // 3] * 3, rows, mono=(0, 1, 2), row_h=320040)

def blank_table(s, x, y, procs, w=COL_RW):
    rows = [["Διεργασία", "Αρχίζει", "Τελειώνει", "Αναμονή"]] + [[n, "", "", ""] for n, _, _ in procs]
    return table(s, x, y, [w // 4] * 4, rows, mono=(0,), row_h=320040)

def exercise(num_, n, kicker, title, text, procs, total, foot, side=None):
    """διαφάνεια άσκησης Gantt: εκφώνηση, δεδομένα, άδειο Gantt, πίνακας και μέσος όρος"""
    s = new(num_, kicker, title, lab=[n])
    y = prompt(s, L, TOP, W, text) + 182880
    label(s, COL_L, y, COL_W, "ΔΕΔΟΜΕΝΑ")
    b = data_table(s, COL_L, y + 283464, procs)
    blanks = " + ".join(["___"] * len(procs))
    if side: card(s, COL_L, b + 228600, COL_W - 914400, *side)
    else: card(s, COL_L, b + 228600, COL_W - 914400, "Μέσος χρόνος αναμονής", f"( {blanks} ) / {len(procs)} = ___", tone="gold")
    label(s, COL_R - 457200, y, COL_RW, "ΔΙΑΓΡΑΜΜΑ GANTT", GOLD)
    b = grid(s, COL_R - 457200, y + 283464, COL_RW + 457200, total)
    blank_table(s, COL_R - 457200, b + 91440, procs, COL_RW + 457200)
    footer(s, "ΣΤΟ SITE", foot)
    return s

def solutions(num_, title, items, foot):
    """items: [(αρ. άσκησης, τίτλος, procs, alg)] — Gantt + αναμονές για καθεμία"""
    s = new(num_, "ΛΥΣΕΙΣ", title)
    y = TOP
    gap = 182880 if len(items) == 3 else 365760
    for n, t, procs, alg in items:
        segs, res = schedule(procs, alg)
        label(s, L, y, W, f"ΑΣΚΗΣΗ {n} · {t.upper()}", GOLD)
        b = gantt(s, L, y + 265176, W, segs)
        tf = box(s, L, b, W, 274320, MSO_ANCHOR.MIDDLE)
        waits = ", ".join(f"{p[0]} = {res[p[0]][2]}" for p in procs)
        rich(tf.paragraphs[0], f"Αναμονές: {waits}   →   μέσος όρος = {avg_line(procs, res)}", 12, TEXT)
        y = b + 274320 + gap
    footer(s, "ΘΥΜΗΣΟΥ", foot)
    return s

