def schedule(procs, alg):
    """procs: [(όνομα, άφιξη, εκτέλεση)] → (κομμάτια Gantt, {όνομα: (αρχίζει, τελειώνει, αναμονή)}, βήματα [(στιγμή, περιμένουν, τρέχει, γιατί)])"""
    t, rem, segs, res, steps = 0, list(procs), [], {}, []
    while rem:
        ready = [p for p in rem if p[1] <= t]
        if not ready:
            nt = min(p[1] for p in rem)
            steps.append((t, "καμία", "—", f"Δεν έχει φτάσει καμία: ο επεξεργαστής μένει **άδειος** ως το {nt}"))
            segs.append((None, t, nt)); t = nt
            continue
        alone = ("Μόνη της: οι άλλες **δεν έχουν φτάσει** ακόμα" if len(rem) > 1 else "Η **τελευταία** που έμεινε")
        if alg == "fcfs":
            p = min(ready, key=lambda p: p[1])
            same = all(q[1] == ready[0][1] for q in ready)
            wait = ", ".join(q[0] if same else f"{q[0]} (ήρθε {q[1]})" for q in ready)
            if len(ready) == 1: why = alone
            elif sum(q[1] == p[1] for q in ready) > 1: why = "Ήρθαν μαζί: πάει η **πρώτη στη σειρά**"
            else: why = f"**Ήρθε πρώτη** (στο {p[1]})"
        else:
            p = min(ready, key=lambda p: (p[2], p[1]))
            wait = ", ".join(f"{q[0]} ({q[2]})" for q in ready)
            tie = [q[0] for q in ready if q is not p and q[2] == p[2]]
            if len(ready) == 1: why = alone
            elif tie: why = f"Ισοπαλία με {tie[0]} ({p[2]}): πάει όποια **ήρθε νωρίτερα**"
            else: why = f"Η **πιο σύντομη** από όσες περιμένουν ({p[2]})"
        steps.append((t, wait, f"{p[0]} ({t}–{t + p[2]})", why))
        segs.append((p[0], t, t + p[2]))
        res[p[0]] = (t, t + p[2], t - p[1])
        t += p[2]
        rem.remove(p)
    return segs, res, steps

def num(x):
    return str(round(x)) if abs(x - round(x)) < 1e-9 else f"{x:.2f}".rstrip("0").replace(".", ",")

def avg_line(procs, res):
    w = [res[p[0]][2] for p in procs]
    return f"({' + '.join(map(str, w))}) / {len(w)} = **{num(sum(w) / len(w))}**"

